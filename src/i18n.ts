import type { Currency, Factory, Grade, Lang } from './types';

export function getLocalizedFactoryName(f: Pick<Factory, 'nameZh' | 'nameEn' | 'nameVi'>, lang: Lang): string {
  if (lang === 'zh') return f.nameZh;
  if (lang === 'vi') return f.nameVi || f.nameEn || f.nameZh;
  return f.nameEn || f.nameZh;
}

export function getLocalizedGradeName(g: Pick<Grade, 'nameZh' | 'nameEn' | 'nameVi'>, lang: Lang): string {
  if (lang === 'zh') return g.nameZh;
  if (lang === 'vi') return g.nameVi || g.nameEn || g.nameZh;
  return g.nameEn || g.nameZh;
}

export function getLocalizedGradeSpec(g: Pick<Grade, 'specZh' | 'specEn' | 'specVi'>, lang: Lang): string {
  if (lang === 'zh') return g.specZh;
  if (lang === 'vi') return g.specVi || g.specEn || g.specZh;
  return g.specEn || g.specZh;
}

export function formatCurrency(amount: number, currency: Currency): string {
  if (currency === 'USD') {
    return `$${amount.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
  }
  if (currency === 'VND') {
    return `${Math.round(amount).toLocaleString('en-US')} ₫`;
  }
  return `¥${amount.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}

export function formatWeightKg(kg: number): string {
  return kg.toLocaleString('en-US', { minimumFractionDigits: 0, maximumFractionDigits: 2 });
}

export function formatWeightTons(kg: number): string {
  return (kg / 1000).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

export function currencySymbol(currency: Currency): string {
  if (currency === 'USD') return '$';
  if (currency === 'VND') return '₫';
  return '¥';
}

